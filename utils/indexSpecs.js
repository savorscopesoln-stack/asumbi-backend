const colName = (k) => k.trim().split(/\s+/)[0];

function buildIndexBlock([table, name, keys, include]) {
  const keyNames = keys.map(colName);
  const allCols = [...keyNames, ...include];
  const colChecks = allCols.map((c) => `COL_LENGTH(N'${table}', N'${c}') IS NOT NULL`).join("\n  AND ");
  // "an existing index already leads with these exact key columns" (covers
  // UNIQUE constraints and indexes created by older migrations).
  const leadChecks = keyNames
    .map(
      (c, i) => `EXISTS (SELECT 1 FROM sys.index_columns ic${i}
        JOIN sys.columns c${i} ON c${i}.object_id = ic${i}.object_id AND c${i}.column_id = ic${i}.column_id
        WHERE ic${i}.object_id = ix.object_id AND ic${i}.index_id = ix.index_id
          AND ic${i}.key_ordinal = ${i + 1} AND c${i}.name = N'${c}')`
    )
    .join("\n        AND ");
  const create =
    `CREATE NONCLUSTERED INDEX ${name} ON ${table} (${keys.join(", ")})` +
    (include.length ? ` INCLUDE (${include.join(", ")})` : "");
  return `-- ${name}
IF OBJECT_ID(N'${table}', N'U') IS NOT NULL
  AND ${colChecks}
  AND NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'${name}' AND object_id = OBJECT_ID(N'${table}'))
  AND NOT EXISTS (
    SELECT 1 FROM sys.indexes ix
    WHERE ix.object_id = OBJECT_ID(N'${table}') AND ix.index_id > 0
      AND ${leadChecks}
  )
BEGIN
  BEGIN TRY
    EXEC(N'${create}');
    PRINT N'created ${name}';
  END TRY
  BEGIN CATCH
    PRINT N'index skipped ${name}: ' + ERROR_MESSAGE();
  END CATCH
END`;
}

const MIGRATION_HEADER = `-- 2026-10-19 — add missing indexes
--
-- GENERATED from backend/utils/indexSpecs.js by
-- backend/scripts/generateIndexMigration.js — do not edit by hand
-- (tests/indexSpecs.test.js fails if this file and the code disagree).
--
-- Idempotent and non-destructive: plain CREATE NONCLUSTERED INDEX only.
-- Each index is skipped when its table/columns don't exist, when an index of
-- the same name exists, or when an existing index / UNIQUE constraint already
-- leads with the same key columns. A failure on one index never stops the rest.
-- The same indexes are also created automatically at server start-up by
-- ensureSchema() -> ensureIndexes(), so running this by hand is optional
-- (useful to build them off-hours on a large production database).
`;

function buildMigrationText() {
  return MIGRATION_HEADER + "\n" + INDEX_SPECS.map(buildIndexBlock).join("\n\n") + "\n";
}

/* Runs every block against the tenant DB. Never throws. Returns
   { created: [...], skipped: [...] } parsed from the PRINT output. */
async function ensureIndexes(pool) {
  const result = { created: [], skipped: [] };
  for (const spec of INDEX_SPECS) {
    try {
      const request = pool.request();
      if (typeof request.on === "function") {
        request.on("info", (info) => {
          const msg = (info && info.message) || "";
          if (msg.startsWith("created ")) result.created.push(msg.slice(8));
          else if (msg.startsWith("index skipped ")) {
            result.skipped.push(msg.slice(14));
            console.warn(`[ensureIndexes] ${msg}`);
          }
        });
      }
      await request.query(buildIndexBlock(spec));
    } catch (e) {
      result.skipped.push(`${spec[1]}: ${e.message}`);
      console.warn(`[ensureIndexes] ${spec[1]} skipped:`, e.message);
    }
  }
  if (result.created.length) {
    console.log(`✅ ensureIndexes: created ${result.created.length} index(es): ${result.created.join(", ")}`);
  }
  return result;
}

