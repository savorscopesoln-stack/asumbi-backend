/* =========================================================
   INDEX SPECS — the missing non-clustered indexes
   ---------------------------------------------------------
   Single source of truth for every index added by the
   "proper indexing" pass. It feeds:
     1. ensureIndexes(pool)  — called at the end of ensureSchema() on every
        boot, for every tenant database.
     2. buildMigrationText() — the text of
        migrations/2026-10-19_add_missing_indexes.sql (generated by
        scripts/generateIndexMigration.js and guarded by
        tests/indexSpecs.test.js so the .sql can't drift from this file).

   Every index is created defensively, so this is safe on ANY tenant DB:
     - skipped if the table doesn't exist,
     - skipped if any key/INCLUDE column doesn't exist (core tables such as
       Students/Teachers/Users have no CREATE TABLE in this repo, so their
       column names are verified at run time rather than assumed),
     - skipped if an index with the same name exists,
     - skipped if ANY existing index or UNIQUE constraint already has these
       key columns as its leading keys (so we never build a duplicate of a
       UNIQUE constraint or of an index from an older migration),
     - wrapped in TRY/CATCH: a failure (e.g. an NVARCHAR(MAX) column that
       can't be a key) prints a message and never blocks startup.
   Plain CREATE INDEX only: nothing here changes data, constraints or results.
========================================================= */

